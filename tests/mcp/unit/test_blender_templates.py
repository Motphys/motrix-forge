def _capture(monkeypatch, call, *args, **kwargs):
    captured = {}

    def fake_call_blender(code, *unused_args, **unused_kwargs):
        captured["code"] = code
        return {"code": code}

    monkeypatch.setattr(importlib.import_module(call.__module__), "call_blender", fake_call_blender)
    call(*args, **kwargs)
    return captured["code"]


