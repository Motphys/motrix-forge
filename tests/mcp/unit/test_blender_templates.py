def test_attach_and_include_release_the_modal_slot_on_sync_completion(monkeypatch):
    """An operator that finishes without going modal must free the modal slot.

    It claims the slot in `begin_modal_operation`; clearing only the deferred
    flag leaves it claimed, and every later operation is refused as
    "already running" for the rest of the session.
    """
    attach_code = _capture(monkeypatch, create.create_attach, "model.xml")
    include_code = _capture(monkeypatch, create.create_include, "common.xml")

    for code in (attach_code, include_code):
        # `rsplit` because `cancel_operation` has an `else:` of its own.
        sync_completion = code.rsplit("else:", 1)[1]
        assert "props.modal_operation_deferred = False" in sync_completion
        assert "if props.modal_operation_active and props.modal_operation_status != 'RUNNING':" in sync_completion
        assert "props.modal_operation_active = False" in sync_completion
        assert 'props.modal_operation_token = ""' in sync_completion


