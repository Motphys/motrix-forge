def test_known_forge_operators_track_the_addon():
    """`_KNOWN_FORGE_OPERATORS` must equal the addon's registered `forge.*` operators.

    The set only exists to disambiguate calls routed through an unknown
    ``bpy.ops`` namespace, so a stale entry silently drops the skill
    requirement for that operator. Parsing the addon source with ``ast`` keeps
    ``bl_idname`` examples inside docstrings out of the comparison.
    """
    if not _ADDON_SOURCE.is_dir():
        pytest.skip("Forge addon source is not part of this checkout")

    registered = set()
    for path in _ADDON_SOURCE.rglob("*.py"):
        for node in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
            if not isinstance(node, (ast.Assign, ast.AnnAssign)):
                continue
            value = node.value
            if (
                isinstance(value, ast.Constant)
                and isinstance(value.value, str)
                and value.value.startswith("forge.")
                and value.value.count(".") == 1
            ):
                registered.add(value.value.split(".", 1)[1])

    assert registered, "no forge.* operator bl_idname found in the addon source"
    assert registered == set(_KNOWN_FORGE_OPERATORS)


