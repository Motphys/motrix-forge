# --- Widget 4: Link (uses view-oriented matrix) ---
def _link_matrix(obj, context: Context):
    """Compute a view-oriented matrix for the link gizmo.

    Builds a 4x4 matrix from the current 3D viewport rotation, placing
    the gizmo at the object's world-space translation. This keeps the
    link widget facing the camera regardless of the object's own rotation.
    """

    rv3d = context.region_data
    if rv3d is None:
        return normalized_object_matrix(obj)
    view_quat = rv3d.view_rotation
    mat = view_quat.to_matrix().to_4x4()
    mat.translation = obj.matrix_world.translation
    return mat


